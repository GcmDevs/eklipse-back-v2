export const fetchComportamientoRobotQuery = () => `
    SELECT
        f.USUARIOID,
        gu.USUDESCRI AS FACTURADOR,
        r.OID AS ROL_ID,
        r.NOMBRE AS ROL,
        COUNT(fa.OID) AS TOTAL_ASIGNADAS,
        ISNULL(SUM(CASE
            WHEN fa.OID IS NULL THEN 0
            WHEN DATEDIFF(DAY, ing.AINFECING, eg.ADEFECSAL) < 1 THEN 1
            ELSE DATEDIFF(DAY, ing.AINFECING, eg.ADEFECSAL)
        END), 0) AS TOTAL_DIAS,
        ROW_NUMBER() OVER (PARTITION BY r.OID ORDER BY f.USUARIOID) AS TURNO_INICIAL
    FROM EKSLNEGRFACTUR f
    INNER JOIN EKSLNEGRROLFACT r ON r.OID = f.ROLFACTURADOR
    INNER JOIN GENUSUARIO gu ON gu.OID = f.USUARIOID
    LEFT JOIN EKSLNEGRFACASIG fa
        ON fa.USUARIOASIGNADO = f.USUARIOID
        AND fa.ESTADO = 2
        AND fa.FECHA >= @0
        AND fa.FECHA < DATEADD(DAY, 1, CAST(@0 AS DATE))
        AND fa.OBSERVACION = 'Asignación automática avanzada'
    LEFT JOIN ADNINGRESO ing ON ing.AINCONSEC = fa.ADNINGRESO
    OUTER APPLY (
        SELECT TOP (1) e.ADEFECSAL
        FROM ADNEGRESO e
        WHERE e.ADNINGRESO = ing.OID
        ORDER BY e.ADEFECSAL DESC, e.OID DESC
    ) eg
    WHERE f.ACTIVO = 1
    GROUP BY f.USUARIOID, gu.USUDESCRI, r.OID, r.NOMBRE
    ORDER BY r.OID, TOTAL_DIAS, TOTAL_ASIGNADAS, f.USUARIOID
`;

export const fetchDetalleComportamientoRobotQuery = () => `
    WITH CUENTAS AS (
        SELECT
            fa.OID AS ASIGNACION_ID,
            fa.ADNINGRESO AS NUMERO_INGRESO,
            fa.USUARIOASIGNADO,
            fa.FECHA AS FECHA_ASIGNACION,
            paciente.GPANOMCOM AS PACIENTE,
            r.OID AS ROL_ID,
            CASE ing.AINESTADO
                WHEN 0 THEN 'REGISTRADO'
                WHEN 1 THEN 'FACTURADO'
                WHEN 2 THEN 'ANULADO'
                WHEN 3 THEN 'BLOQUEADO'
                WHEN 4 THEN 'CIERRE ADMINISTRATIVO'
                ELSE 'SIN ESTADO'
            END AS ESTADO_INGRESO,
            CASE
                WHEN DATEDIFF(DAY, ing.AINFECING, eg.ADEFECSAL) < 1 THEN 1
                ELSE DATEDIFF(DAY, ing.AINFECING, eg.ADEFECSAL)
            END AS DIAS_ESTANCIA,
            CASE
                WHEN ing.AINURGCON IN (10, 11) AND ing.AINCAUING = 11
                    AND EXISTS (
                        SELECT 1 FROM PCNPROSAL ps
                        INNER JOIN PCNSALAS sala ON sala.OID = ps.PSSALA
                        WHERE ps.ADNINGRESO = ing.OID AND ps.PSESTADO IN (0, 1, 3)
                          AND sala.SALCODIGO IN ('AC10', 'AC11', 'AC12', 'AC13')
                    ) THEN 'HEMODINAMIA'
                WHEN UPPER(ISNULL(er.ADESNOMBRE, '')) LIKE '%CIRUG%' THEN 'PQX'
                WHEN EXISTS (
                    SELECT 1 FROM HPNESTANC est
                    INNER JOIN HPNDEFCAM def ON def.OID = est.HPNDEFCAM
                    INNER JOIN HPNSUBGRU hps ON hps.OID = def.HPNSUBGRU
                    WHERE est.ADNINGRES = ing.OID AND hps.HSUUCI = '1'
                ) THEN 'UCI'
                WHEN ing.GEENUSUARIO = 6661 THEN 'ONCO'
                ELSE 'NORMAL'
            END AS TIPO_FACTURA
        FROM EKSLNEGRFACASIG fa
        INNER JOIN EKSLNEGRFACTUR f ON f.USUARIOID = fa.USUARIOASIGNADO AND f.ACTIVO = 1
        INNER JOIN EKSLNEGRROLFACT r ON r.OID = f.ROLFACTURADOR
        INNER JOIN GENUSUARIO gu ON gu.OID = f.USUARIOID
        LEFT JOIN ADNINGRESO ing ON ing.AINCONSEC = fa.ADNINGRESO
        LEFT JOIN GENPACIEN paciente ON paciente.OID = ing.GENPACIEN
        OUTER APPLY (
            SELECT TOP (1) e.ADEFECSAL, e.ADNEGRESER
            FROM ADNEGRESO e
            WHERE e.ADNINGRESO = ing.OID
            ORDER BY e.ADEFECSAL DESC, e.OID DESC
        ) eg
        LEFT JOIN ADNEGRESER er ON er.OID = eg.ADNEGRESER
        WHERE fa.USUARIOASIGNADO = @0
          AND fa.FECHA >= @1
          AND fa.FECHA < DATEADD(DAY, 1, CAST(@1 AS DATE))
          AND fa.ESTADO = 2
          AND fa.OBSERVACION = 'Asignación automática avanzada'
    ), AUDITORIA AS (
        SELECT ASIGNACION_ID, NUMERO_INGRESO, USUARIOASIGNADO, FECHA_ASIGNACION, PACIENTE,
            ESTADO_INGRESO, DIAS_ESTANCIA, TIPO_FACTURA,
            CASE
                WHEN TIPO_FACTURA = 'HEMODINAMIA' AND ROL_ID = 7 THEN 'CORRECTO'
                WHEN TIPO_FACTURA = 'PQX' AND ROL_ID = 1 THEN 'CORRECTO'
                WHEN TIPO_FACTURA = 'UCI' AND ROL_ID = 3 THEN 'CORRECTO'
                WHEN TIPO_FACTURA = 'ONCO' AND ROL_ID = 4 THEN 'CORRECTO'
                WHEN TIPO_FACTURA = 'NORMAL' AND DIAS_ESTANCIA > 2 AND ROL_ID IN (2, 3) THEN 'CORRECTO'
                WHEN TIPO_FACTURA = 'NORMAL' AND DIAS_ESTANCIA <= 2 AND ROL_ID IN (3, 5) THEN 'CORRECTO'
                ELSE 'REVISAR'
            END AS VALIDACION_ASIGNACION
        FROM CUENTAS
    )
    SELECT * FROM AUDITORIA
    ORDER BY CASE WHEN VALIDACION_ASIGNACION = 'REVISAR' THEN 0 ELSE 1 END,
        FECHA_ASIGNACION DESC, ASIGNACION_ID DESC
`;

