const fetchCuentasPorFacturadorQuery = (finalizadas: boolean) => `
    SELECT
        EKSLNEGRFACASIG.OID AS ASIGNACION_ID,
        ADNINGRESO.AINCONSEC AS NUMERO_INGRESO,
        ADNEGRESO.ADENUMEGR AS NUMERO_EGRESO,
        CASE ADNINGRESO.ADNCENATE
            WHEN 1 THEN 'CENTRO MEDICO'
            WHEN 2 THEN 'ALTA COMPLEJIDAD'
            WHEN 3 THEN 'CAPS'
        END AS SEDE,
        ADNINGRESO.ADNCENATE,
        ADNINGRESO.AINFECING AS FECHA_INGRESO,
        ADNEGRESO.ADEFECSAL AS FECHA_EGRESO,
        CASE ADNINGRESO.AINURGCON
            WHEN 0 THEN 'URGENCIA'
            WHEN 1 THEN 'CONSULTA EXTERNA'
            WHEN 2 THEN 'NACIDO HOSPITAL'
            WHEN 3 THEN 'REMITIDO'
            WHEN 4 THEN 'HOSPITALIZACIÓN URGENCIA'
            WHEN 5 THEN 'HOSPITALIZACION'
            WHEN 6 THEN 'IMAGENES'
            WHEN 7 THEN 'LABORATORIO'
            WHEN 8 THEN 'URGENCIA GINECOLOGICA'
            WHEN 9 THEN 'QUIROFANO'
            WHEN 10 THEN 'CIRUGÍA AMBULATORIA'
            WHEN 11 THEN 'CIRUGÍA PROGRAMADA'
        END AS INGRESO_POR,
        GENPACIEN.GPANOMCOM AS PACIENTE,
        GENUSUARIO.USUDESCRI AS USUARIO_CREO_EGRESO,
        GENROL.ROLNOMBRE AS ROL_USUARIO,
        EKSLNEGRFACASIG.TIPOCUENTA,
        EKSLNEGRFACASIG.OBSERVACION AS OBSERVACIONASIGNAR,
        EKSLNEGRFACASIG.USUARIOASIGNADO,
        EKSLNEGRFACASIG.FECHA AS FECHA_ASIGNACION,
        EKSLNEGRFACASIG.FECHA AS FECHAREGISTROASIGNADO,
        ADNINGRESO.AINESTADO AS ESTADO_ADNINGRESO,
        CASE
            WHEN DATEDIFF(DAY, ADNINGRESO.AINFECING, ADNEGRESO.ADEFECSAL) < 1 THEN 1
            ELSE DATEDIFF(DAY, ADNINGRESO.AINFECING, ADNEGRESO.ADEFECSAL)
        END AS DIAS_ESTANCIA,
        DATEDIFF(DAY, ADNEGRESO.ADEFECSAL, GETDATE()) AS dias_desde_egreso
    FROM EKSLNEGRFACASIG
    INNER JOIN ADNINGRESO ON ADNINGRESO.AINCONSEC = EKSLNEGRFACASIG.ADNINGRESO
    INNER JOIN GENPACIEN ON GENPACIEN.OID = ADNINGRESO.GENPACIEN
    OUTER APPLY (
        SELECT TOP (1) eg.ADENUMEGR, eg.ADEFECSAL, eg.GEENUSUARIO
        FROM ADNEGRESO eg
        WHERE eg.ADNINGRESO = ADNINGRESO.OID
        ORDER BY eg.ADEFECSAL DESC, eg.OID DESC
    ) ADNEGRESO
    LEFT JOIN GENUSUARIO ON GENUSUARIO.OID = ADNEGRESO.GEENUSUARIO
    LEFT JOIN GENROL ON GENROL.OID = GENUSUARIO.GENROL
    WHERE EKSLNEGRFACASIG.USUARIOASIGNADO = @0
      AND EKSLNEGRFACASIG.FECHA >= @1
      AND EKSLNEGRFACASIG.FECHA < DATEADD(DAY, 1, CAST(@2 AS DATE))
      AND ${
        finalizadas
          ? '(ADNINGRESO.AINESTADO = 1 OR EKSLNEGRFACASIG.ESTADO = 3) AND ADNINGRESO.AINESTADO NOT IN (2, 4)'
          : 'EKSLNEGRFACASIG.ESTADO = 2 AND ADNINGRESO.AINESTADO IN (0, 3)'
      }
    ORDER BY EKSLNEGRFACASIG.FECHA DESC, EKSLNEGRFACASIG.OID DESC
`;

