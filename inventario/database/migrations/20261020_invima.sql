-- Ejecutar en cada base de datos de contexto que habilite Verificación INVIMA.
SET XACT_ABORT ON;
BEGIN TRANSACTION;
IF OBJECT_ID('EKINNIVPRODUCTO', 'U') IS NULL
BEGIN
  CREATE TABLE EKINNIVPRODUCTO (
    OID INT IDENTITY(1,1) PRIMARY KEY, DATOS NVARCHAR(MAX) NOT NULL,
    VERSION INT NOT NULL, ULTIMAVERIFICACION INT NULL,
    CREADOPOR INT NOT NULL, FECHACREA DATETIME2 NOT NULL, FECHAACT DATETIME2 NOT NULL,
    CONSTRAINT CK_IV_PRODUCTO_JSON CHECK (ISJSON(DATOS) = 1)
  );
  CREATE TABLE EKINNIVVERIFICACION (
    OID INT IDENTITY(1,1) PRIMARY KEY, PRODUCTOID INT NOT NULL,
    VERSIONPRODUCTO INT NOT NULL, ENTRADA NVARCHAR(MAX) NOT NULL,
    RESULTADO VARCHAR(30) NOT NULL, EVIDENCIA NVARCHAR(MAX) NOT NULL,
    USUARIOID INT NOT NULL, USUARIONOMBRE NVARCHAR(240) NOT NULL, FECHA DATETIME2 NOT NULL,
    CONSTRAINT FK_IV_VERIFICACION_PRODUCTO FOREIGN KEY (PRODUCTOID) REFERENCES EKINNIVPRODUCTO(OID),
    CONSTRAINT CK_IV_VERIFICACION_JSON CHECK (ISJSON(ENTRADA) = 1 AND ISJSON(EVIDENCIA) = 1)
  );
  CREATE INDEX IX_IV_VERIFICACION_PRODUCTO ON EKINNIVVERIFICACION (PRODUCTOID, OID DESC);
  ALTER TABLE EKINNIVPRODUCTO ADD CONSTRAINT FK_IV_PRODUCTO_ULTIMA FOREIGN KEY (ULTIMAVERIFICACION) REFERENCES EKINNIVVERIFICACION(OID);
  CREATE TABLE EKINNIVCONFIRMACION (
    OID INT IDENTITY(1,1) PRIMARY KEY, VERIFICACIONID INT NOT NULL,
    CANDIDATO NVARCHAR(MAX) NOT NULL, USUARIOID INT NOT NULL,
    USUARIONOMBRE NVARCHAR(240) NOT NULL, FECHA DATETIME2 NOT NULL,
    CONSTRAINT UQ_IV_CONFIRMACION UNIQUE (VERIFICACIONID),
    CONSTRAINT FK_IV_CONFIRMACION_VERIFICACION FOREIGN KEY (VERIFICACIONID) REFERENCES EKINNIVVERIFICACION(OID),
    CONSTRAINT CK_IV_CONFIRMACION_JSON CHECK (ISJSON(CANDIDATO) = 1)
  );
END;
-- Registrar el permiso sin concederlo automáticamente a usuarios o roles.
DECLARE @modulo INT = (SELECT TOP 1 OID FROM EKGENMODULO WHERE CODIGO = '006');
DECLARE @submodulo INT = (SELECT TOP 1 OID FROM EKGENSUBMODULO WHERE CODIGO = '005' AND EKGENMODULO = @modulo);
IF @modulo IS NULL OR @submodulo IS NULL
  THROW 50001, 'No existe el módulo Inventario / Productos para registrar el permiso INVIMA.', 1;
IF EXISTS (SELECT 1 FROM GCMMODULOS WHERE EKGENMODULO = @modulo AND EKGENSUBMODULO = @submodulo AND EKCODIGO = '002' AND NOMBRE <> N'VERIFICACIÓN INVIMA')
  THROW 50002, 'El permiso 006005002 ya está ocupado por otra funcionalidad. Revisar antes de habilitar INVIMA.', 1;
IF NOT EXISTS (SELECT 1 FROM GCMMODULOS WHERE EKGENMODULO = @modulo AND EKGENSUBMODULO = @submodulo AND EKCODIGO = '002')
  INSERT INTO GCMMODULOS (EKCODIGO, NOMBRE, ACTIVO, EKGENMODULO, EKGENSUBMODULO)
    VALUES ('002', N'VERIFICACIÓN INVIMA', 1, @modulo, @submodulo);
COMMIT TRANSACTION;
