SET XACT_ABORT ON;
BEGIN TRANSACTION;
IF OBJECT_ID('EKINNIVPRODUCTO', 'U') IS NULL
  THROW 50003, 'Falta la migración inicial de Verificación INVIMA.', 1;
IF OBJECT_ID('EKINNIVFACTURA', 'U') IS NULL
BEGIN
  CREATE TABLE EKINNIVFACTURA (
    OID INT IDENTITY(1,1) PRIMARY KEY,
    NUMERO NVARCHAR(100) NOT NULL, PROVEEDOR NVARCHAR(240) NOT NULL, NITPROVEEDOR VARCHAR(30) NOT NULL,
    FECHA DATE NULL, FORMATO VARCHAR(30) NOT NULL, EXTRACTORVERSION VARCHAR(30) NOT NULL,
    ARCHIVONOMBRE NVARCHAR(260) NOT NULL, ARCHIVOHASH VARCHAR(64) NOT NULL, PAGINAS INT NOT NULL,
    ADVERTENCIAS NVARCHAR(MAX) NOT NULL, ESTADO VARCHAR(20) NOT NULL, VERSION INT NOT NULL,
    CREADOPOR INT NOT NULL, ACTUALIZADOPOR INT NOT NULL,
    FECHACREA DATETIME2 NOT NULL, FECHAACT DATETIME2 NOT NULL,
    CONSTRAINT CK_IV_FACTURA_JSON CHECK(ISJSON(ADVERTENCIAS) = 1),
    CONSTRAINT UQ_IV_FACTURA_HASH UNIQUE(ARCHIVOHASH)
  );
  CREATE INDEX IX_IV_FACTURA_LISTADO ON EKINNIVFACTURA(OID DESC);
END;
IF OBJECT_ID('EKINNIVFACTURAITEM', 'U') IS NULL
BEGIN
  CREATE TABLE EKINNIVFACTURAITEM (
    OID INT IDENTITY(1,1) PRIMARY KEY, FACTURAID INT NOT NULL, PRODUCTOID INT NULL,
    ORDEN INT NOT NULL, ORIGINAL NVARCHAR(MAX) NOT NULL, DATOS NVARCHAR(MAX) NOT NULL, EXCLUIDO BIT NOT NULL,
    CONSTRAINT FK_IV_ITEM_FACTURA FOREIGN KEY(FACTURAID) REFERENCES EKINNIVFACTURA(OID),
    CONSTRAINT FK_IV_ITEM_PRODUCTO FOREIGN KEY(PRODUCTOID) REFERENCES EKINNIVPRODUCTO(OID),
    CONSTRAINT CK_IV_ITEM_JSON CHECK(ISJSON(ORIGINAL) = 1 AND ISJSON(DATOS) = 1),
    CONSTRAINT UQ_IV_ITEM_ORDEN UNIQUE(FACTURAID, ORDEN)
  );
  CREATE UNIQUE INDEX UQ_IV_ITEM_PRODUCTO ON EKINNIVFACTURAITEM(PRODUCTOID) WHERE PRODUCTOID IS NOT NULL;
END;
COMMIT TRANSACTION;
