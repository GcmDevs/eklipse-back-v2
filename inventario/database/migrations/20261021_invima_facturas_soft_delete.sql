SET XACT_ABORT ON;
BEGIN TRANSACTION;
IF OBJECT_ID('EKINNIVFACTURA', 'U') IS NULL
  THROW 50004, 'Falta la migración de facturas INVIMA.', 1;
IF COL_LENGTH('EKINNIVFACTURA', 'FECHAELIMINA') IS NULL
  ALTER TABLE EKINNIVFACTURA ADD FECHAELIMINA DATETIME2 NULL;
IF COL_LENGTH('EKINNIVFACTURA', 'ELIMINADOPOR') IS NULL
  ALTER TABLE EKINNIVFACTURA ADD ELIMINADOPOR INT NULL;
IF EXISTS (SELECT 1 FROM sys.key_constraints WHERE parent_object_id = OBJECT_ID('EKINNIVFACTURA') AND name = 'UQ_IV_FACTURA_HASH')
  ALTER TABLE EKINNIVFACTURA DROP CONSTRAINT UQ_IV_FACTURA_HASH;
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID('EKINNIVFACTURA') AND name = 'UQ_IV_FACTURA_HASH_ACTIVA')
  EXEC(N'CREATE UNIQUE INDEX UQ_IV_FACTURA_HASH_ACTIVA ON EKINNIVFACTURA(ARCHIVOHASH) WHERE FECHAELIMINA IS NULL');
COMMIT TRANSACTION;
