-- Migración única de Verificación INVIMA. SQL Server 2016 o superior.
-- Ejecutar completa en la base de cada contexto antes de desplegar el backend.
-- Crea una instalación nueva o completa las migraciones anteriores sin borrar datos.
-- Puede repetirse. No asigna permisos a usuarios/roles ni reactiva permisos deshabilitados.
SET NOCOUNT ON;
SET XACT_ABORT ON;
SET ANSI_NULLS ON;
SET QUOTED_IDENTIFIER ON;
SET ANSI_PADDING ON;
SET ANSI_WARNINGS ON;
SET CONCAT_NULL_YIELDS_NULL ON;
SET ARITHABORT ON;
SET NUMERIC_ROUNDABORT OFF;

BEGIN TRY
  BEGIN TRANSACTION;

  -- Resolver los identificadores locales; no asumir los OID de otro contexto.
  IF OBJECT_ID(N'dbo.EKGENMODULO', N'U') IS NULL
     OR OBJECT_ID(N'dbo.EKGENSUBMODULO', N'U') IS NULL
     OR OBJECT_ID(N'dbo.GCMMODULOS', N'U') IS NULL
    THROW 50001, 'Falta el esquema de seguridad de Eklipse en la base activa.', 1;

  IF (SELECT COUNT(*) FROM dbo.EKGENMODULO WHERE CODIGO = '006') <> 1
    THROW 50001, 'Debe existir un único módulo Inventario (006) en la base activa.', 1;

  DECLARE @modulo INT = (SELECT OID FROM dbo.EKGENMODULO WHERE CODIGO = '006');
  IF (SELECT COUNT(*) FROM dbo.EKGENSUBMODULO WHERE CODIGO = '005' AND EKGENMODULO = @modulo) <> 1
    THROW 50001, 'Debe existir un único submódulo Productos (005) de Inventario.', 1;

  DECLARE @submodulo INT = (
    SELECT OID FROM dbo.EKGENSUBMODULO WHERE CODIGO = '005' AND EKGENMODULO = @modulo
  );
  IF (SELECT COUNT(*) FROM dbo.GCMMODULOS
      WHERE EKGENMODULO = @modulo AND EKGENSUBMODULO = @submodulo AND EKCODIGO = '002') > 1
    THROW 50002, 'El permiso 006005002 está duplicado. Revisar antes de habilitar INVIMA.', 1;
  IF EXISTS (
    SELECT 1 FROM dbo.GCMMODULOS
    WHERE EKGENMODULO = @modulo AND EKGENSUBMODULO = @submodulo AND EKCODIGO = '002'
      AND (NOMBRE IS NULL OR NOMBRE <> N'VERIFICACIÓN INVIMA')
  )
    THROW 50002, 'El permiso 006005002 pertenece a otra funcionalidad. No se modificó.', 1;

  IF OBJECT_ID(N'dbo.EKINNIVPRODUCTO', N'U') IS NULL
    CREATE TABLE dbo.EKINNIVPRODUCTO (
      OID INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_IV_PRODUCTO PRIMARY KEY,
      DATOS NVARCHAR(MAX) NOT NULL,
      VERSION INT NOT NULL,
      ULTIMAVERIFICACION INT NULL,
      CREADOPOR INT NOT NULL,
      FECHACREA DATETIME2 NOT NULL,
      FECHAACT DATETIME2 NOT NULL
    );

  IF OBJECT_ID(N'dbo.EKINNIVVERIFICACION', N'U') IS NULL
    CREATE TABLE dbo.EKINNIVVERIFICACION (
      OID INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_IV_VERIFICACION PRIMARY KEY,
      PRODUCTOID INT NOT NULL,
      VERSIONPRODUCTO INT NOT NULL,
      ENTRADA NVARCHAR(MAX) NOT NULL,
      RESULTADO VARCHAR(30) NOT NULL,
      EVIDENCIA NVARCHAR(MAX) NOT NULL,
      USUARIOID INT NOT NULL,
      USUARIONOMBRE NVARCHAR(240) NOT NULL,
      FECHA DATETIME2 NOT NULL
    );

  IF OBJECT_ID(N'dbo.EKINNIVCONFIRMACION', N'U') IS NULL
    CREATE TABLE dbo.EKINNIVCONFIRMACION (
      OID INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_IV_CONFIRMACION PRIMARY KEY,
      VERIFICACIONID INT NOT NULL,
      CANDIDATO NVARCHAR(MAX) NOT NULL,
      USUARIOID INT NOT NULL,
      USUARIONOMBRE NVARCHAR(240) NOT NULL,
      FECHA DATETIME2 NOT NULL
    );

  IF OBJECT_ID(N'dbo.EKINNIVFACTURA', N'U') IS NULL
    CREATE TABLE dbo.EKINNIVFACTURA (
      OID INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_IV_FACTURA PRIMARY KEY,
      NUMERO NVARCHAR(100) NOT NULL,
      PROVEEDOR NVARCHAR(240) NOT NULL,
      NITPROVEEDOR VARCHAR(30) NOT NULL,
      FECHA DATE NULL,
      FORMATO VARCHAR(30) NOT NULL,
      EXTRACTORVERSION VARCHAR(30) NOT NULL,
      ARCHIVONOMBRE NVARCHAR(260) NOT NULL,
      ARCHIVOHASH VARCHAR(64) NOT NULL,
      PAGINAS INT NOT NULL,
      ADVERTENCIAS NVARCHAR(MAX) NOT NULL,
      ESTADO VARCHAR(20) NOT NULL,
      VERSION INT NOT NULL,
      CREADOPOR INT NOT NULL,
      ACTUALIZADOPOR INT NOT NULL,
      FECHACREA DATETIME2 NOT NULL,
      FECHAACT DATETIME2 NOT NULL,
      FECHAELIMINA DATETIME2 NULL,
      ELIMINADOPOR INT NULL,
      OBSERVACION NVARCHAR(MAX) NOT NULL CONSTRAINT DF_IV_FACTURA_OBS DEFAULT N'',
      OBSVERSION INT NOT NULL CONSTRAINT DF_IV_FACTURA_OBSV DEFAULT 0,
      OBSUSUARIO INT NULL,
      OBSNOMBRE NVARCHAR(240) NULL,
      OBSFECHA DATETIME2 NULL,
      TIPODOCUMENTO VARCHAR(20) NOT NULL CONSTRAINT DF_IV_FACTURA_TIPODOC DEFAULT 'FACTURA',
      CLIENTE NVARCHAR(240) NOT NULL CONSTRAINT DF_IV_FACTURA_CLIENTE DEFAULT N''
    );

  IF OBJECT_ID(N'dbo.EKINNIVFACTURAITEM', N'U') IS NULL
    CREATE TABLE dbo.EKINNIVFACTURAITEM (
      OID INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_IV_FACTURAITEM PRIMARY KEY,
      FACTURAID INT NOT NULL,
      PRODUCTOID INT NULL,
      ORDEN INT NOT NULL,
      ORIGINAL NVARCHAR(MAX) NOT NULL,
      DATOS NVARCHAR(MAX) NOT NULL,
      EXCLUIDO BIT NOT NULL,
      OBSERVACION NVARCHAR(MAX) NOT NULL CONSTRAINT DF_IV_ITEM_OBS DEFAULT N'',
      OBSVERSION INT NOT NULL CONSTRAINT DF_IV_ITEM_OBSV DEFAULT 0,
      OBSUSUARIO INT NULL,
      OBSNOMBRE NVARCHAR(240) NULL,
      OBSFECHA DATETIME2 NULL
    );

  -- Actualizar instalaciones anteriores, incluso si faltan columnas por separado.
  IF COL_LENGTH(N'dbo.EKINNIVFACTURA', N'FECHAELIMINA') IS NULL
    ALTER TABLE dbo.EKINNIVFACTURA ADD FECHAELIMINA DATETIME2 NULL;
  IF COL_LENGTH(N'dbo.EKINNIVFACTURA', N'ELIMINADOPOR') IS NULL
    ALTER TABLE dbo.EKINNIVFACTURA ADD ELIMINADOPOR INT NULL;
  IF COL_LENGTH(N'dbo.EKINNIVFACTURA', N'OBSERVACION') IS NULL
    ALTER TABLE dbo.EKINNIVFACTURA ADD OBSERVACION NVARCHAR(MAX) NOT NULL
      CONSTRAINT DF_IV_FACTURA_OBS DEFAULT N'';
  IF COL_LENGTH(N'dbo.EKINNIVFACTURA', N'OBSVERSION') IS NULL
    ALTER TABLE dbo.EKINNIVFACTURA ADD OBSVERSION INT NOT NULL
      CONSTRAINT DF_IV_FACTURA_OBSV DEFAULT 0;
  IF COL_LENGTH(N'dbo.EKINNIVFACTURA', N'OBSUSUARIO') IS NULL
    ALTER TABLE dbo.EKINNIVFACTURA ADD OBSUSUARIO INT NULL;
  IF COL_LENGTH(N'dbo.EKINNIVFACTURA', N'OBSNOMBRE') IS NULL
    ALTER TABLE dbo.EKINNIVFACTURA ADD OBSNOMBRE NVARCHAR(240) NULL;
  IF COL_LENGTH(N'dbo.EKINNIVFACTURA', N'OBSFECHA') IS NULL
    ALTER TABLE dbo.EKINNIVFACTURA ADD OBSFECHA DATETIME2 NULL;
  IF COL_LENGTH(N'dbo.EKINNIVFACTURA', N'TIPODOCUMENTO') IS NULL
    ALTER TABLE dbo.EKINNIVFACTURA ADD TIPODOCUMENTO VARCHAR(20) NOT NULL
      CONSTRAINT DF_IV_FACTURA_TIPODOC DEFAULT 'FACTURA';
  IF COL_LENGTH(N'dbo.EKINNIVFACTURA', N'CLIENTE') IS NULL
    ALTER TABLE dbo.EKINNIVFACTURA ADD CLIENTE NVARCHAR(240) NOT NULL
      CONSTRAINT DF_IV_FACTURA_CLIENTE DEFAULT N'';

  IF COL_LENGTH(N'dbo.EKINNIVFACTURAITEM', N'OBSERVACION') IS NULL
    ALTER TABLE dbo.EKINNIVFACTURAITEM ADD OBSERVACION NVARCHAR(MAX) NOT NULL
      CONSTRAINT DF_IV_ITEM_OBS DEFAULT N'';
  IF COL_LENGTH(N'dbo.EKINNIVFACTURAITEM', N'OBSVERSION') IS NULL
    ALTER TABLE dbo.EKINNIVFACTURAITEM ADD OBSVERSION INT NOT NULL
      CONSTRAINT DF_IV_ITEM_OBSV DEFAULT 0;
  IF COL_LENGTH(N'dbo.EKINNIVFACTURAITEM', N'OBSUSUARIO') IS NULL
    ALTER TABLE dbo.EKINNIVFACTURAITEM ADD OBSUSUARIO INT NULL;
  IF COL_LENGTH(N'dbo.EKINNIVFACTURAITEM', N'OBSNOMBRE') IS NULL
    ALTER TABLE dbo.EKINNIVFACTURAITEM ADD OBSNOMBRE NVARCHAR(240) NULL;
  IF COL_LENGTH(N'dbo.EKINNIVFACTURAITEM', N'OBSFECHA') IS NULL
    ALTER TABLE dbo.EKINNIVFACTURAITEM ADD OBSFECHA DATETIME2 NULL;

  -- Integridad de la evidencia y relaciones, también en instalaciones parciales.
  IF NOT EXISTS (SELECT 1 FROM sys.check_constraints WHERE parent_object_id = OBJECT_ID(N'dbo.EKINNIVPRODUCTO') AND name = N'CK_IV_PRODUCTO_JSON')
    ALTER TABLE dbo.EKINNIVPRODUCTO WITH CHECK ADD CONSTRAINT CK_IV_PRODUCTO_JSON CHECK (ISJSON(DATOS) = 1);
  IF NOT EXISTS (SELECT 1 FROM sys.check_constraints WHERE parent_object_id = OBJECT_ID(N'dbo.EKINNIVVERIFICACION') AND name = N'CK_IV_VERIFICACION_JSON')
    ALTER TABLE dbo.EKINNIVVERIFICACION WITH CHECK ADD CONSTRAINT CK_IV_VERIFICACION_JSON CHECK (ISJSON(ENTRADA) = 1 AND ISJSON(EVIDENCIA) = 1);
  IF NOT EXISTS (SELECT 1 FROM sys.check_constraints WHERE parent_object_id = OBJECT_ID(N'dbo.EKINNIVCONFIRMACION') AND name = N'CK_IV_CONFIRMACION_JSON')
    ALTER TABLE dbo.EKINNIVCONFIRMACION WITH CHECK ADD CONSTRAINT CK_IV_CONFIRMACION_JSON CHECK (ISJSON(CANDIDATO) = 1);
  IF NOT EXISTS (SELECT 1 FROM sys.check_constraints WHERE parent_object_id = OBJECT_ID(N'dbo.EKINNIVFACTURA') AND name = N'CK_IV_FACTURA_JSON')
    ALTER TABLE dbo.EKINNIVFACTURA WITH CHECK ADD CONSTRAINT CK_IV_FACTURA_JSON CHECK (ISJSON(ADVERTENCIAS) = 1);
  IF NOT EXISTS (SELECT 1 FROM sys.check_constraints WHERE parent_object_id = OBJECT_ID(N'dbo.EKINNIVFACTURAITEM') AND name = N'CK_IV_ITEM_JSON')
    ALTER TABLE dbo.EKINNIVFACTURAITEM WITH CHECK ADD CONSTRAINT CK_IV_ITEM_JSON CHECK (ISJSON(ORIGINAL) = 1 AND ISJSON(DATOS) = 1);

  IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE parent_object_id = OBJECT_ID(N'dbo.EKINNIVVERIFICACION') AND name = N'FK_IV_VERIFICACION_PRODUCTO')
    ALTER TABLE dbo.EKINNIVVERIFICACION WITH CHECK ADD CONSTRAINT FK_IV_VERIFICACION_PRODUCTO FOREIGN KEY (PRODUCTOID) REFERENCES dbo.EKINNIVPRODUCTO(OID);
  IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE parent_object_id = OBJECT_ID(N'dbo.EKINNIVPRODUCTO') AND name = N'FK_IV_PRODUCTO_ULTIMA')
    ALTER TABLE dbo.EKINNIVPRODUCTO WITH CHECK ADD CONSTRAINT FK_IV_PRODUCTO_ULTIMA FOREIGN KEY (ULTIMAVERIFICACION) REFERENCES dbo.EKINNIVVERIFICACION(OID);
  IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE parent_object_id = OBJECT_ID(N'dbo.EKINNIVCONFIRMACION') AND name = N'FK_IV_CONFIRMACION_VERIFICACION')
    ALTER TABLE dbo.EKINNIVCONFIRMACION WITH CHECK ADD CONSTRAINT FK_IV_CONFIRMACION_VERIFICACION FOREIGN KEY (VERIFICACIONID) REFERENCES dbo.EKINNIVVERIFICACION(OID);
  IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE parent_object_id = OBJECT_ID(N'dbo.EKINNIVFACTURAITEM') AND name = N'FK_IV_ITEM_FACTURA')
    ALTER TABLE dbo.EKINNIVFACTURAITEM WITH CHECK ADD CONSTRAINT FK_IV_ITEM_FACTURA FOREIGN KEY (FACTURAID) REFERENCES dbo.EKINNIVFACTURA(OID);
  IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE parent_object_id = OBJECT_ID(N'dbo.EKINNIVFACTURAITEM') AND name = N'FK_IV_ITEM_PRODUCTO')
    ALTER TABLE dbo.EKINNIVFACTURAITEM WITH CHECK ADD CONSTRAINT FK_IV_ITEM_PRODUCTO FOREIGN KEY (PRODUCTOID) REFERENCES dbo.EKINNIVPRODUCTO(OID);

  IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID(N'dbo.EKINNIVVERIFICACION') AND name = N'IX_IV_VERIFICACION_PRODUCTO')
    CREATE INDEX IX_IV_VERIFICACION_PRODUCTO ON dbo.EKINNIVVERIFICACION(PRODUCTOID, OID DESC);
  IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID(N'dbo.EKINNIVCONFIRMACION') AND name = N'UQ_IV_CONFIRMACION')
    ALTER TABLE dbo.EKINNIVCONFIRMACION ADD CONSTRAINT UQ_IV_CONFIRMACION UNIQUE(VERIFICACIONID);
  IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID(N'dbo.EKINNIVFACTURA') AND name = N'IX_IV_FACTURA_LISTADO')
    CREATE INDEX IX_IV_FACTURA_LISTADO ON dbo.EKINNIVFACTURA(OID DESC);
  IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID(N'dbo.EKINNIVFACTURAITEM') AND name = N'UQ_IV_ITEM_ORDEN')
    ALTER TABLE dbo.EKINNIVFACTURAITEM ADD CONSTRAINT UQ_IV_ITEM_ORDEN UNIQUE(FACTURAID, ORDEN);
  IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID(N'dbo.EKINNIVFACTURAITEM') AND name = N'UQ_IV_ITEM_PRODUCTO')
    CREATE UNIQUE INDEX UQ_IV_ITEM_PRODUCTO ON dbo.EKINNIVFACTURAITEM(PRODUCTOID) WHERE PRODUCTOID IS NOT NULL;

  -- Reemplaza solo la unicidad antigua; conserva facturas eliminadas y su evidencia.
  IF EXISTS (SELECT 1 FROM sys.key_constraints WHERE parent_object_id = OBJECT_ID(N'dbo.EKINNIVFACTURA') AND name = N'UQ_IV_FACTURA_HASH')
    ALTER TABLE dbo.EKINNIVFACTURA DROP CONSTRAINT UQ_IV_FACTURA_HASH;
  ELSE IF EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID(N'dbo.EKINNIVFACTURA') AND name = N'UQ_IV_FACTURA_HASH')
    DROP INDEX UQ_IV_FACTURA_HASH ON dbo.EKINNIVFACTURA;
  IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID(N'dbo.EKINNIVFACTURA') AND name = N'UQ_IV_FACTURA_HASH_ACTIVA')
    EXEC(N'CREATE UNIQUE INDEX UQ_IV_FACTURA_HASH_ACTIVA ON dbo.EKINNIVFACTURA(ARCHIVOHASH) WHERE FECHAELIMINA IS NULL');

  IF NOT EXISTS (
    SELECT 1 FROM dbo.GCMMODULOS WITH (UPDLOCK, HOLDLOCK)
    WHERE EKGENMODULO = @modulo AND EKGENSUBMODULO = @submodulo AND EKCODIGO = '002'
  )
    INSERT INTO dbo.GCMMODULOS (EKCODIGO, NOMBRE, ACTIVO, EKGENMODULO, EKGENSUBMODULO)
      VALUES ('002', N'VERIFICACIÓN INVIMA', 1, @modulo, @submodulo);

  COMMIT TRANSACTION;
END TRY
BEGIN CATCH
  IF XACT_STATE() <> 0 ROLLBACK TRANSACTION;
  THROW;
END CATCH;
