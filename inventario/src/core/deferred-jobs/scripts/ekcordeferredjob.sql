IF OBJECT_ID(N'dbo.EKCORTRABAJODIF', N'U') IS NULL
BEGIN
  CREATE TABLE dbo.EKCORTRABAJODIF (
    OID          INT            NOT NULL IDENTITY(1,1),
    KEY_JOB      VARCHAR(200)   NOT NULL,
    ESPACIO      VARCHAR(80)    NOT NULL,
    CONTEXTO     VARCHAR(40)    NOT NULL,
    CLAVE        VARCHAR(120)   NOT NULL,
    EJECUTAEN    DATETIME2      NOT NULL,
    CUERPO       NVARCHAR(MAX)  NOT NULL,
    ESTADO       VARCHAR(20)    NOT NULL,
    INTENTOS     INT            NOT NULL CONSTRAINT DF_EKCORTRABAJODIF_INTENTOS DEFAULT (0),
    MAXINTENTOS  INT            NOT NULL CONSTRAINT DF_EKCORTRABAJODIF_MAXINTENTOS DEFAULT (5),
    ULTERROR     NVARCHAR(500)  NULL,
    PROXINTENTO  DATETIME2      NOT NULL,
    CREATEDAT    DATETIME2      NOT NULL,
    UPDATEDAT    DATETIME2      NOT NULL,
    CONSTRAINT PK_EKCORTRABAJODIF PRIMARY KEY (OID),
    CONSTRAINT UQ_EKCORTRABAJODIF_KEY_JOB UNIQUE (KEY_JOB)
  );

  CREATE INDEX IX_EKCORTRABAJODIF_DUE
    ON dbo.EKCORTRABAJODIF (CONTEXTO, ESTADO, PROXINTENTO);
END
ELSE IF COL_LENGTH(N'dbo.EKCORTRABAJODIF', N'LLAVE') IS NOT NULL
  AND COL_LENGTH(N'dbo.EKCORTRABAJODIF', N'KEY_JOB') IS NULL
BEGIN
  IF OBJECT_ID(N'dbo.UQ_EKCORTRABAJODIF_LLAVE', N'UQ') IS NOT NULL
    ALTER TABLE dbo.EKCORTRABAJODIF DROP CONSTRAINT UQ_EKCORTRABAJODIF_LLAVE;

  EXEC sp_rename N'dbo.EKCORTRABAJODIF.LLAVE', N'KEY_JOB', N'COLUMN';

  ALTER TABLE dbo.EKCORTRABAJODIF
    ADD CONSTRAINT UQ_EKCORTRABAJODIF_KEY_JOB UNIQUE (KEY_JOB);
END
GO
