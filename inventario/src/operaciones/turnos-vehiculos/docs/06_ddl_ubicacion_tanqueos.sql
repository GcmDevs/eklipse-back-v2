/* ---------- 3. CHECK sobre UBICVALRESULTADO ---------- */
IF NOT EXISTS (SELECT 1 FROM sys.check_constraints WHERE name = 'CK_GCNTANQUEOS_UBICVALRESULTADO')
BEGIN
    DECLARE @sql nvarchar(max) = N'
        ALTER TABLE GCNTANQUEOS WITH CHECK
        ADD CONSTRAINT CK_GCNTANQUEOS_UBICVALRESULTADO
        CHECK (
            UBICVALRESULTADO IS NULL OR UBICVALRESULTADO IN (
                N''DENTRO_RADIO'',
                N''FUERA_RADIO'',
                N''DISCREPANCIA'',
                N''NO_CONCLUYENTE'',
                N''NO_VALIDADO''
            )
        );
    ';
    EXEC sp_executesql @sql;
    PRINT '  -> CK_GCNTANQUEOS_UBICVALRESULTADO creado';
END
GO

/* ---------- 4. Índice para filtro resultadoUbicacion ---------- */
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_GCNTANQUEOS_UBICVALRESULTADO' AND object_id = OBJECT_ID('GCNTANQUEOS'))
BEGIN
    EXEC sp_executesql N'
        CREATE INDEX IX_GCNTANQUEOS_UBICVALRESULTADO
        ON GCNTANQUEOS (UBICVALRESULTADO)
        WHERE UBICVALRESULTADO IS NOT NULL;
    ';
    PRINT '  -> IX_GCNTANQUEOS_UBICVALRESULTADO creado';
END
GO

/* ---------- 4. Ampliar CHECK de GCNTANQUEOINCONS.CODIGO ---------- */
DECLARE @ckName sysname;
DECLARE @dropSql nvarchar(400);

SELECT @ckName = cc.name
FROM sys.check_constraints cc
LEFT JOIN sys.columns c ON c.object_id = cc.parent_object_id AND c.column_id = cc.parent_column_id
WHERE cc.parent_object_id = OBJECT_ID('GCNTANQUEOINCONS')
      AND (c.name = 'CODIGO' OR cc.definition LIKE '%CODIGO%');

IF @ckName IS NOT NULL
BEGIN
    SET @dropSql = N'ALTER TABLE GCNTANQUEOINCONS DROP CONSTRAINT ' + QUOTENAME(@ckName);
    EXEC sp_executesql @dropSql;
    PRINT '  -> CK_GCNTANQUEOINCONS antiguo eliminado';
END

ALTER TABLE GCNTANQUEOINCONS WITH CHECK
ADD CONSTRAINT CK_GCNTANQUEOINCONS_CODIGO
CHECK (
    CODIGO IN (
        N'EVID_SIN_FOTO',
        N'EVID_REC_OMIT',
        N'EVID_ODO_OMIT',
        N'KM_MENOR_ANT',
        N'KM_SALTO',
        N'CANT_COMB_CAP',
        N'VALOR_ALTO_INU',
        N'TQ_DUP',
        N'UBIC_FUERA_RAD',
        N'UBIC_DISCREP',
        N'UBIC_NO_CONC'
    )
);
PRINT '  -> CK_GCNTANQUEOINCONS_CODIGO actualizado';
