  ALTER TABLE AMBTURNO DROP CONSTRAINT CK_AMBTURNO_CAUSACIERRE;
ALTER TABLE AMBTURNO ADD CONSTRAINT CK_AMBTURNO_CAUSACIERRE
  CHECK (CAUSACIERRE IS NULL OR CAUSACIERRE IN (
    'RECEPCION_INICIADA', 'AUSENCIA_RECEPTOR', 'REEMPLAZADO_EXCEPCIONAL', 'SIN_ACTIVIDAD', 'CIERRE_ADMIN'
  ));


-- =============================================================================
-- AMBTURNO: un usuario no puede tener 2 turnos simultáneos (ACTIVO o ENTREGADO)
-- =============================================================================
