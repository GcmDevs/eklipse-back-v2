-- =============================================================================
-- AMBLIMPIEZA
-- =============================================================================
SELECT COUNT(*) AS limpiezas_sin_reportar FROM AMBLIMPIEZA WHERE ESTADO = 'SIN_REPORTAR';
DELETE FROM AMBLIMPIEZA WHERE ESTADO = 'SIN_REPORTAR';

ALTER TABLE AMBLIMPIEZA ADD CAUSACIERRE VARCHAR(15) NULL;

IF EXISTS (SELECT 1 FROM sys.check_constraints WHERE name = 'CK_AMBLIMPIEZA_ESTADO')
  ALTER TABLE AMBLIMPIEZA DROP CONSTRAINT CK_AMBLIMPIEZA_ESTADO;
ALTER TABLE AMBLIMPIEZA ADD CONSTRAINT CK_AMBLIMPIEZA_ESTADO
  CHECK (ESTADO IN ('BORRADOR', 'DILIGENCIADO', 'INCOMPLETO'));

IF EXISTS (SELECT 1 FROM sys.check_constraints WHERE name = 'CK_AMBLIMPIEZA_CAUSACIERRE')
  ALTER TABLE AMBLIMPIEZA DROP CONSTRAINT CK_AMBLIMPIEZA_CAUSACIERRE;
ALTER TABLE AMBLIMPIEZA ADD CONSTRAINT CK_AMBLIMPIEZA_CAUSACIERRE
  CHECK (CAUSACIERRE IS NULL OR CAUSACIERRE IN ('MANUAL', 'VENCIMIENTO', 'CIERRE_ADMIN'));

-- PLANTILLAOID / USUARIOOID: las filas SIN_REPORTAR ya se borraron; el resto debe tener autor.
UPDATE AMBLIMPIEZA SET PLANTILLAOID = 0 WHERE PLANTILLAOID IS NULL;
UPDATE AMBLIMPIEZA SET USUARIOOID = 0 WHERE USUARIOOID IS NULL;
ALTER TABLE AMBLIMPIEZA ALTER COLUMN PLANTILLAOID INT NOT NULL;
ALTER TABLE AMBLIMPIEZA ALTER COLUMN USUARIOOID INT NOT NULL;

-- =============================================================================
-- AMBDOTACION
-- =============================================================================
SELECT COUNT(*) AS dotaciones_sin_verificar FROM AMBDOTACION WHERE ESTADO = 'SIN_VERIFICAR';
DELETE FROM AMBDOTACION WHERE ESTADO = 'SIN_VERIFICAR';

IF EXISTS (SELECT 1 FROM sys.check_constraints WHERE name = 'CK_AMBDOTACION_ESTADO')
  ALTER TABLE AMBDOTACION DROP CONSTRAINT CK_AMBDOTACION_ESTADO;
ALTER TABLE AMBDOTACION ADD CONSTRAINT CK_AMBDOTACION_ESTADO
  CHECK (ESTADO IN ('EN_CURSO', 'CERRADA'));

UPDATE AMBDOTACION SET PLANTILLAOID = 0 WHERE PLANTILLAOID IS NULL;
UPDATE AMBDOTACION SET USUARIOOID = 0 WHERE USUARIOOID IS NULL;
UPDATE AMBDOTACION SET FECHAINICIO = CREATEDAT WHERE FECHAINICIO IS NULL;
UPDATE AMBDOTACION SET FECHALIMITE = CREATEDAT WHERE FECHALIMITE IS NULL;
ALTER TABLE AMBDOTACION ALTER COLUMN PLANTILLAOID INT NOT NULL;
ALTER TABLE AMBDOTACION ALTER COLUMN USUARIOOID INT NOT NULL;
ALTER TABLE AMBDOTACION ALTER COLUMN FECHAINICIO DATETIME2 NOT NULL;
ALTER TABLE AMBDOTACION ALTER COLUMN FECHALIMITE DATETIME2 NOT NULL;

IF EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_AMBDOTACION_FECHALIMITE_PENDIENTE')
  DROP INDEX IX_AMBDOTACION_FECHALIMITE_PENDIENTE ON AMBDOTACION;
CREATE INDEX IX_AMBDOTACION_FECHALIMITE_PENDIENTE
  ON AMBDOTACION (FECHALIMITE)
  WHERE BLOQUEADA = 0;

IF COL_LENGTH('AMBDOTACION', 'EXTENDIDO') IS NULL
  ALTER TABLE AMBDOTACION ADD EXTENDIDO BIT NOT NULL CONSTRAINT DF_AMBDOTACION_EXTENDIDO DEFAULT 0;

-- =============================================================================
-- AMBDOTACIONNOVEDAD
-- =============================================================================
IF EXISTS (SELECT 1 FROM sys.check_constraints WHERE name = 'CK_AMBDOTACIONNOVEDAD_ESTADO')
  ALTER TABLE AMBDOTACIONNOVEDAD DROP CONSTRAINT CK_AMBDOTACIONNOVEDAD_ESTADO;
ALTER TABLE AMBDOTACIONNOVEDAD ADD CONSTRAINT CK_AMBDOTACIONNOVEDAD_ESTADO
