export const USUARIOS_PRE_SQL = `SELECT u.OID id,u.USUDESCRI nombre FROM GENUSUARIO u
WHERE u.USUESTADO=1 AND EXISTS (SELECT 1 FROM GCMMODULOS a
LEFT JOIN EKGENMODULO m ON m.OID=a.EKGENMODULO
LEFT JOIN EKGENSUBMODULO s ON s.OID=a.EKGENSUBMODULO
WHERE a.ACTIVO=1 AND ISNULL(m.ACTIVO,1)=1 AND ISNULL(s.ACTIVO,1)=1
AND (a.EKCODIGO='admin' OR CONCAT(m.CODIGO,s.CODIGO,a.EKCODIGO) IN (@0,@1))
AND (EXISTS (SELECT 1 FROM GCMUSUPERMISO up WHERE up.IDUSUARIO=u.OID AND up.IDMODULO=a.OID)
OR EXISTS (SELECT 1 FROM GCMMODULOROL rp WHERE rp.GENROL=u.GENROL AND rp.GCMMODULO=a.OID)))
ORDER BY u.USUDESCRI,u.OID`;
