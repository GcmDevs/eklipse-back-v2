export const INGRESO_PRE_SQL = `SELECT TOP (2) i.OID oid, CONVERT(varchar(20),i.AINCONSEC) ingreso,
  p.OID pacienteId, CONCAT(p.PACPRINOM,' ',p.PACSEGNOM,' ',p.PACPRIAPE,' ',p.PACSEGAPE) nombre,
  p.PACNUMDOC documento,p.PACTIPDOC tipoDocumento,i.ADNCENATE centroId,c.ACANOMBRE centro,
  CONVERT(varchar(23),i.AINFECING,126) fechaIngreso,CONVERT(varchar(23),i.AINFECEGRE,126) fechaEgreso,
  e.ENTCODIGO entidadCodigo,e.ENTNOMBRE entidad,i.AINESTADO estadoClinico
FROM ADNINGRESO i INNER JOIN GENPACIEN p ON p.OID=i.GENPACIEN
LEFT JOIN ADNCENATE c ON c.OID=i.ADNCENATE
LEFT JOIN GENDETCON dc ON dc.OID=i.GENDETCON
LEFT JOIN GENCONTRA co ON co.OID=dc.GENCONTRA1
LEFT JOIN GEENENTADM e ON e.OID=co.DGNENTADM1
WHERE i.AINCONSEC=@0 ORDER BY i.OID`;

