  OID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
  CODIGO VARCHAR(50) NOT NULL UNIQUE,
  NOMBRE VARCHAR(100) NOT NULL,
  ORDEN INT NOT NULL UNIQUE,
