CREATE TABLE EKHPNCIRSEG (
  OID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
  PCNCONSEC VARCHAR(50) NOT NULL,
  ESTADOACTUAL VARCHAR(50) NOT NULL,
  FECHAINICIOPREPARACION DATETIME NULL,
  FECHAINICIOCIRUGIA DATETIME NULL,
  FECHAINICIORECUPERACION DATETIME NULL,
  FECHAFINALIZACION DATETIME NULL,
  USUARIOMODIFICACIONID BIGINT NOT NULL,
  USUARIOMODIFICACIONNOMBRE VARCHAR(150) NOT NULL CONSTRAINT DF_CIRUGIASEGUIMIENTO_USUARIO DEFAULT '',
  CREATEDAT DATETIME NOT NULL CONSTRAINT DF_CIRUGIASEGUIMIENTO_CREATED DEFAULT GETDATE(),
  UPDATEDAT DATETIME NOT NULL CONSTRAINT DF_CIRUGIASEGUIMIENTO_UPDATED DEFAULT GETDATE(),
  CONSTRAINT UX_CIRUGIASEGUIMIENTO_CONSEC UNIQUE (PCNCONSEC),
  CONSTRAINT FK_CIRUGIASEGUIMIENTO_ESTADO FOREIGN KEY (ESTADOACTUAL) REFERENCES EKHPNCIREST(CODIGO)
);
GO
CREATE TABLE EKHPNCIRHIS (
  OID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
  PCNCONSEC VARCHAR(50) NOT NULL,
  ESTADOANTERIOR VARCHAR(50) NOT NULL,
  ESTADONUEVO VARCHAR(50) NOT NULL,
  USUARIOID BIGINT NOT NULL,
  USUARIONOMBRE VARCHAR(150) NOT NULL CONSTRAINT DF_CIRUGIAHISTORIAL_USUARIO DEFAULT '',
  FECHAHORA DATETIME NOT NULL CONSTRAINT DF_CIRUGIAHISTORIAL_FECHA DEFAULT GETDATE(),
  CONSTRAINT FK_CIRUGIAHISTORIAL_ANTERIOR FOREIGN KEY (ESTADOANTERIOR) REFERENCES EKHPNCIREST(CODIGO),
  CONSTRAINT FK_CIRUGIAHISTORIAL_NUEVO FOREIGN KEY (ESTADONUEVO) REFERENCES EKHPNCIREST(CODIGO)
);
GO
CREATE INDEX IX_CIRUGIAHISTORIAL_CONSEC ON EKHPNCIRHIS (PCNCONSEC);
GO
